import assert from 'node:assert/strict';
import { newCard, review, isDue, isMastered, rungFor, pickRung, ratingFor, isKnown, TUNING } from './srs.js';
const now = new Date('2026-10-17T10:00:00');
const c = newCard(now);
const K = TUNING.ladder.kana, all = () => true, caps = ({canHear, canSay}) => r => r === 'hear' ? canHear : r === 'say' ? canSay : true;
assert.equal(isDue(c, now), true);
assert.equal(rungFor(c, K, all), 'hear');
assert.equal(rungFor({...c, stability: 5}, K, all), 'see');
assert.equal(rungFor({...c, stability: 12}, K, caps({canHear: true, canSay: false})), 'see');
assert.equal(rungFor(c, K, caps({canHear: false, canSay: false})), 'see');
assert.equal(isMastered({...c, stability: 21}), true);
assert.equal(isMastered({...c, stability: 20.9}), false);
assert.equal(ratingFor({correct: false, ms: 1000}), 1);
assert.equal(ratingFor({correct: true, ms: 9000}), 2);
assert.equal(ratingFor({correct: true, ms: 1000, hinted: true}), 2);
assert.equal(ratingFor({correct: true, ms: 1000, speechFallback: true}), 2);
assert.equal(ratingFor({correct: true, ms: 1000, stretch: true}), 4);
assert.equal(ratingFor({correct: true, ms: 1000}), 3);
const Wd = TUNING.ladder.word;
assert.equal(rungFor({...c, stability: 5}, Wd, r => r !== 'read'), 'see');
assert.equal(rungFor({...c, stability: 30}, Wd, r => r !== 'say'), 'tiles');
const G = TUNING.ladder.grammar;
assert.equal(rungFor(c, G, r => r !== 'form'), 'fill');
assert.equal(rungFor(c, G, r => r === 'build'), 'build');
assert.equal(rungFor(c, G, () => false), null);
assert.deepEqual(pickRung({...c, stability: 5}, Wd, r => r !== 'tiles', () => 0.1), {rung: 'say', stretch: true});
assert.equal(ratingFor({correct: true, ms: 14000, rung: 'tiles'}), 3);
assert.equal(ratingFor({correct: true, ms: 9000, rung: 'see'}), 2);
assert.equal(isKnown({...c, stability: 3}), true);
const next = review(c, 3, now);
assert.ok(next.due > now && next.reps === 1);
assert.deepEqual(pickRung({...c, stability: 5}, K, caps({canHear: true, canSay: true}), () => 0.1), {rung: 'say', stretch: true});
assert.deepEqual(pickRung({...c, stability: 5}, K, caps({canHear: true, canSay: false}), () => 0.1), {rung: 'see', stretch: false});
assert.deepEqual(pickRung({...c, stability: 5}, K, caps({canHear: true, canSay: true}), () => 0.9), {rung: 'see', stretch: false});
// cards survive JSON (Task 3 revives dates)
assert.equal(JSON.parse(JSON.stringify(next)).reps, 1);
